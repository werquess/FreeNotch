import AppKit
import Observation

@MainActor
@Observable
final class ClipboardMonitor {
    enum Content: Equatable {
        case text(String)
        case image(NSImage)
        case files([URL])
    }

    struct Entry: Identifiable, Equatable {
        let id = UUID()
        let content: Content
        let date: Date
        let sourceApp: String?

        var previewText: String {
            switch content {
            case .text(let s): s.trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: "\n", with: " ")
            case .image: String(localized: "Image")
            case .files(let urls): urls.map(\.lastPathComponent).joined(separator: ", ")
            }
        }

        var symbol: String {
            switch content {
            case .text(let s): s.hasPrefix("http") ? "link" : "text.alignleft"
            case .image: "photo"
            case .files: "doc"
            }
        }
    }

    private(set) var entries: [Entry] = []
    var isPaused = false

    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: DispatchSourceTimer?

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword"
    ]

    init() {
        let saved = UserDefaults.standard.stringArray(forKey: Prefs.Key.clipboardTexts.rawValue) ?? []
        entries = saved.map { Entry(content: .text($0), date: .distantPast, sourceApp: nil) }
    }

    func start() {
        guard timer == nil else { return }
        let t = DispatchSource.makeTimerSource(queue: .main)
        t.schedule(deadline: .now() + 1, repeating: .milliseconds(800), leeway: .milliseconds(500))
        t.setEventHandler { [weak self] in
            MainActor.assumeIsolated { self?.poll() }
        }
        t.resume()
        timer = t
    }

    func stop() {
        timer?.cancel()
        timer = nil
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        guard !isPaused, Prefs.bool(.clipboardEnabled) else { return }

        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        let source = NSWorkspace.shared.frontmostApplication?.localizedName
        let content: Content?
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            content = .files(urls)
        } else if let s = pb.string(forType: .string), !s.isEmpty {
            content = .text(s)
        } else if let image = NSImage(pasteboard: pb) {
            content = .image(image.thumbnail(maxSide: 240))
        } else {
            content = nil
        }
        guard let content else { return }
        insert(Entry(content: content, date: .now, sourceApp: source))
    }

    private func insert(_ entry: Entry) {
        if case .text = entry.content {
            entries.removeAll { $0.content == entry.content }
        }
        entries.insert(entry, at: 0)
        let limit = max(5, Prefs.int(.clipboardLimit))
        if entries.count > limit { entries.removeLast(entries.count - limit) }
        persist()
    }

    func copy(_ entry: Entry) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch entry.content {
        case .text(let s): pb.setString(s, forType: .string)
        case .image(let img): pb.writeObjects([img])
        case .files(let urls): pb.writeObjects(urls as [NSURL])
        }
        lastChangeCount = pb.changeCount
        entries.removeAll { $0.id == entry.id }
        entries.insert(Entry(content: entry.content, date: .now, sourceApp: entry.sourceApp), at: 0)
        persist()
    }

    func delete(_ entry: Entry) {
        entries.removeAll { $0.id == entry.id }
        persist()
    }

    func clear() {
        entries.removeAll()
        persist()
    }

    private func persist() {
        let texts = entries.compactMap { e -> String? in
            if case .text(let s) = e.content, s.count < 10_000 { return s }
            return nil
        }
        UserDefaults.standard.set(texts, forKey: Prefs.Key.clipboardTexts.rawValue)
    }
}

extension NSImage {
    func thumbnail(maxSide: CGFloat) -> NSImage {
        let scale = min(1, maxSide / max(size.width, size.height, 1))
        guard scale < 1 else { return self }
        let target = NSSize(width: size.width * scale, height: size.height * scale)
        return NSImage(size: target, flipped: false) { rect in
            self.draw(in: rect)
            return true
        }
    }
}
